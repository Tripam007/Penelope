// Backward-compatible alias for village array
export const MOCK_VILLAGES = MOCK_LANDMARKS;

export function generateGeoJsonFeatureCollection() {
  const features = [];

  // 1. All Landmark Points (Villages, Towns, Tourist Spots, Treks, Bridges, Shelters)
  for (const lmk of MOCK_LANDMARKS) {
    let layerType = "village";
    if (lmk.type === "shelter") layerType = "shelter";
    else if (lmk.type === "town") layerType = "town";
    else if (lmk.type === "tourist_spot" || lmk.type === "landmark") layerType = "landmark";
    else if (lmk.type === "trek") layerType = "trek";
    else if (lmk.type === "bridge") layerType = "bridge";

    features.push({
      type: "Feature",
      geometry: {
        type: "Point",
        coordinates: [lmk.lng, lmk.lat]
      },
      properties: {
        id: lmk.id,
        name: lmk.name,
        hindi_name: lmk.hindi_name,
        type: lmk.type,
        category: lmk.category,
        layer_type: layerType,
        elevation_m: lmk.elevation_m,
        ground_height_m: lmk.ground_height_m,
        slope_degrees: lmk.slope_degrees,
        river_distance_m: lmk.river_distance_m,
        population: lmk.population,
        risk_score: lmk.current_risk_score,
        risk_level: lmk.risk_level,
        trend: lmk.trend,
        // Open-Meteo Rain Features
        rain_1h_mm: lmk.rain_1h_mm,
        rain_3h_mm: lmk.rain_3h_mm,
        rain_6h_mm: lmk.rain_6h_mm,
        rain_24h_mm: lmk.rain_24h_mm,
        peak_rain_rate_mmh: lmk.peak_rain_rate_mmh,
        antecedent_index: lmk.antecedent_index,
        // Soil Ratios
        soil_ratios: lmk.soil_ratios,
        // GloFAS River Features
        river_discharge_m3s: lmk.river_discharge_m3s,
        river_anomaly_m3s: lmk.river_anomaly_m3s,
        river_anomaly_ratio: lmk.river_anomaly_ratio,
        capacity: lmk.capacity,
        contact_person: lmk.contact_person,
        contact_phone: lmk.contact_phone,
        status: lmk.status,
      }
    });
  }

  // 2. Sensor Features
  for (const s of MOCK_SENSORS) {
    features.push({
      type: "Feature",
      geometry: {
        type: "Point",
        coordinates: [s.lng, s.lat]
      },
      properties: {
        id: s.id,
        name: s.name,
        category: "sensor",
        layer_type: "sensor",
        river_name: s.river_name,
        water_level_m: s.water_level_m,
        danger_level_m: s.danger_level_m,
        warning_level_m: s.warning_level_m,
        status: s.status,
        discharge_m3s: s.discharge_m3s,
        river_discharge_m3s: s.discharge_m3s,
        river_anomaly_m3s: Math.round(s.discharge_m3s - 220.0),
        rainfall_1h_mm: s.rainfall_1h_mm,
        battery_pct: s.battery_pct,
      }
    });
  }

  // 3. Evacuation Route LineStrings
  const routes = [
    { from: [79.6931, 30.4856], to: [79.5620, 30.5590], name: "Raini to Joshimath Safe Ridge Corridor" },
    { from: [79.5772, 30.5639], to: [79.5620, 30.5590], name: "Vishnuprayag to Town Hall Relief Shelter" },
    { from: [79.5580, 30.6250], to: [79.5520, 30.6280], name: "Govindghat Riverbank to High Ground Camp" }
  ];

  for (const r of routes) {
    features.push({
      type: "Feature",
      geometry: {
        type: "LineString",
        coordinates: [r.from, r.to]
      },
      properties: {
        layer_type: "evacuation_route",
        category: "evacuation_route",
        name: r.name,
        status: "CLEAR"
      }
    });
  }

  return {
    type: "FeatureCollection",
    features
  };
}
